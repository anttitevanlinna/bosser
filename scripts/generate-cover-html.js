#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

class HTMLCoverGenerator {
    constructor() {
        this.width = 1920;
        this.height = 1080;
        
        // Brand colors from site
        this.colors = {
            background: '#0a0a0a',
            accent: '#ff6b35',
            text: '#ffffff',
            textSecondary: '#b3b3b3'
        };
    }
    
    generateCoverHTML(title) {
        return `<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Cover: ${title}</title>
    <style>
        body {
            margin: 0;
            padding: 0;
            width: ${this.width}px;
            height: ${this.height}px;
            background: ${this.colors.background};
            font-family: 'Inter', -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;
            overflow: hidden;
            position: relative;
        }
        
        .cover-container {
            width: 100%;
            height: 100%;
            position: relative;
            display: flex;
            align-items: center;
            padding: 80px;
            box-sizing: border-box;
        }
        
        .content {
            max-width: 70%;
            z-index: 10;
            position: relative;
        }
        
        .subtitle {
            color: ${this.colors.accent};
            font-size: 24px;
            font-weight: 600;
            text-transform: uppercase;
            letter-spacing: 2px;
            margin-bottom: 24px;
        }
        
        .title {
            color: ${this.colors.text};
            font-size: 72px;
            font-weight: 700;
            line-height: 1.1;
            margin-bottom: 32px;
        }
        
        .author {
            color: ${this.colors.textSecondary};
            font-size: 20px;
            font-weight: 400;
        }
        
        .particle-container {
            position: absolute;
            left: 300px;
            top: 0;
            width: 800px;
            height: 100%;
            z-index: 0;
            opacity: 0.6;
        }
        
        .particle {
            position: absolute;
            background: ${this.colors.accent};
            border-radius: 50%;
            transition: all 2s cubic-bezier(0.4, 0, 0.2, 1);
        }
        
        .particle.small { width: 2px; height: 2px; }
        .particle.medium { width: 4px; height: 4px; }
        .particle.large { width: 6px; height: 6px; box-shadow: 0 0 12px ${this.colors.accent}40; }
    </style>
</head>
<body>
    <div class="cover-container">
        <div class="content">
            <div class="subtitle">On Product Leadership Newsletter</div>
            <h1 class="title">${title}</h1>
            <div class="author">Antti Tevanlinna</div>
        </div>
        
        <div class="particle-container" id="particles">
            <!-- Particles generated by JavaScript -->
        </div>
    </div>
    
    <script>
        const particleContainer = document.getElementById('particles');
        const particleCount = 300;
        const particles = [];
        
        // Create particles
        for (let i = 0; i < particleCount; i++) {
            const particle = document.createElement('div');
            particle.className = 'particle ' + ['small', 'medium', 'large'][Math.floor(Math.random() * 3)];
            particle.style.left = Math.random() * 800 + 'px';
            particle.style.top = Math.random() * ${this.height} + 'px';
            particleContainer.appendChild(particle);
            particles.push(particle);
        }
        
        // Shape formations
        function getCloudFormation() {
            const formations = [];
            const centerX = 500;
            const centerY = ${this.height / 2};
            
            for (let i = 0; i < particleCount; i++) {
                const angle = (i / particleCount) * Math.PI * 2 * 3;
                const radius = 225 + Math.sin(angle * 2) * 75;
                formations.push({
                    x: centerX + Math.cos(angle) * radius + (Math.random() - 0.5) * 150,
                    y: centerY + Math.sin(angle) * radius * 0.9 + (Math.random() - 0.5) * 120
                });
            }
            return formations;
        }
        
        function getBrainFormation() {
            const formations = [];
            const centerX = 500;
            const centerY = ${this.height / 2};
            
            for (let i = 0; i < particleCount; i++) {
                const cluster = Math.floor(i / (particleCount / 6));
                const clusterAngle = (cluster / 6) * Math.PI * 2;
                const clusterX = centerX + Math.cos(clusterAngle) * 180;
                const clusterY = centerY + Math.sin(clusterAngle) * 120;
                
                formations.push({
                    x: clusterX + (Math.random() - 0.5) * 120,
                    y: clusterY + (Math.random() - 0.5) * 90
                });
            }
            return formations;
        }
        
        // Mathematical rotation function
        function rotatePoint(x, y, centerX, centerY, angle) {
            const cos = Math.cos(angle);
            const sin = Math.sin(angle);
            const dx = x - centerX;
            const dy = y - centerY;
            return {
                x: centerX + dx * cos - dy * sin,
                y: centerY + dx * sin + dy * cos
            };
        }
        
        // Horizontal arrow formation (reference) - 100% larger
        function getHorizontalArrowFormation() {
            const formations = [];
            const centerX = 500; // Keep horizontal center
            const arrowLength = 400; // 100% larger (was 200)
            const startX = centerX - arrowLength / 2;
            const endX = centerX + arrowLength / 2;
            const startY = ${this.height / 2};
            const endY = ${this.height / 2}; // Same Y = horizontal
            
            for (let i = 0; i < particleCount; i++) {
                const progress = i / particleCount;
                
                if (progress < 0.6) {
                    // Horizontal shaft
                    const shaftX = startX + (endX - startX) * (progress / 0.6);
                    const shaftY = startY;
                    formations.push({ x: shaftX, y: shaftY });
                } else {
                    // Arrow head - standard horizontal V (100% larger)
                    const headProgress = (progress - 0.6) / 0.4;
                    const headTipX = endX;
                    const headTipY = endY;
                    const headSize = 160; // 100% larger (was 80)
                    const headHeight = 120; // 100% larger (was 60)
                    
                    if (headProgress < 0.5) {
                        // Upper wing: from back-up to tip
                        const diagProgress = headProgress / 0.5;
                        const wingBaseX = endX - headSize;
                        const wingBaseY = endY - headHeight;
                        formations.push({
                            x: wingBaseX + diagProgress * headSize,
                            y: wingBaseY + diagProgress * headHeight
                        });
                    } else {
                        // Lower wing: from back-down to tip
                        const diagProgress = (headProgress - 0.5) / 0.5;
                        const wingBaseX = endX - headSize;
                        const wingBaseY = endY + headHeight;
                        formations.push({
                            x: wingBaseX + diagProgress * headSize,
                            y: wingBaseY - diagProgress * headHeight
                        });
                    }
                }
            }
            return formations;
        }
        
        function getArrowFormation() {
            // Start with perfect horizontal arrow
            const horizontalFormations = getHorizontalArrowFormation();
            
            // Rotate mathematically by -45 degrees (clockwise to northeast)
            const rotationAngle = -Math.PI / 4;
            const centerX = 500;
            const centerY = ${this.height / 2};
            
            // Apply rotation and add randomness
            const formations = horizontalFormations.map(point => {
                const rotated = rotatePoint(point.x, point.y, centerX, centerY, rotationAngle);
                return {
                    x: rotated.x + (Math.random() - 0.5) * 8,
                    y: rotated.y + (Math.random() - 0.5) * 8
                };
            });
            
            return formations;
        }
        
        // Animation loop
        const formations = [getCloudFormation(), getBrainFormation(), getArrowFormation()];
        let currentFormationIndex = 0;
        
        function animateParticles() {
            const currentFormation = formations[currentFormationIndex];
            
            particles.forEach((particle, i) => {
                const target = currentFormation[i];
                particle.style.left = target.x + 'px';
                particle.style.top = target.y + 'px';
            });
            
            currentFormationIndex = (currentFormationIndex + 1) % formations.length;
        }
        
        // Start animation
        animateParticles();
        setInterval(animateParticles, 4000);
    </script>
</body>
</html>`;
    }
    
    async generateCover(title, outputDir) {
        console.log(`🎨 Generating HTML cover for: ${title}`);
        
        const coverHTML = this.generateCoverHTML(title);
        const htmlPath = path.join(outputDir, 'cover.html');
        
        fs.writeFileSync(htmlPath, coverHTML);
        
        console.log(`✅ HTML cover generated: ${htmlPath}`);
        console.log(`📖 Open ${htmlPath} in browser to view animated cover`);
        console.log(`🎬 Use browser screen recording to create MP4 for LinkedIn`);
        
        return htmlPath;
    }
}

module.exports = HTMLCoverGenerator;